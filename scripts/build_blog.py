#!/usr/bin/env python3
"""Build opt-in article pages and only the marked new-post area on the homepage."""
from pathlib import Path
from html import escape
import argparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
START = '<!-- BLOG:AUTO:START -->'
END = '<!-- BLOG:AUTO:END -->'

def render(template, values):
    def replace(match):
        key = match.group(1)
        if key not in values:
            raise ValueError(f'Missing template field: {key}')
        return values[key] if key in ('body', 'article_nav') else escape(str(values[key]), quote=True)
    return re.sub(r'\{\{([a-z_]+)\}\}', replace, template)

def outputs():
    posts = json.loads((ROOT / 'data/posts.json').read_text())
    slugs = [p['slug'] for p in posts]
    if len(slugs) != len(set(slugs)) or any(not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', s) for s in slugs):
        raise ValueError('Post slugs must be unique lowercase kebab-case')
    template = (ROOT / 'templates/article.html').read_text()
    result = {}
    entries = []
    for i, post in enumerate(posts):
        if post.get('legacy'):
            if not (ROOT / 'blog' / f"{post['slug']}.html").is_file():
                raise ValueError('Missing legacy article')
            continue
        path = ROOT / 'blog' / f"{post['slug']}.html"
        # Refuse to replace an existing, unmanaged article.
        if path.exists() and '<!-- Generated by scripts/build_blog.py; edit content/ instead. -->' not in path.read_text():
            raise ValueError(f'Refusing to overwrite unmanaged article: {path}')
        nav = ['<a href="../index.html#blog">返回 Blog 目录</a>']
        for j, prefix in [(i-1, '上一篇'), (i+1, '下一篇')]:
            if 0 <= j < len(posts):
                p = posts[j]
                nav.append(f'<a href="{p["slug"]}.html">{prefix}：{escape(p["title"])}</a>')
        values = dict(post, body=(ROOT / 'content' / f"{post['slug']}.html").read_text(), article_nav=''.join(nav))
        result[path] = render(template, values).replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by scripts/build_blog.py; edit content/ instead. -->', 1)
        entries.append(f'''    <div class="publication">
        <div class="publication-title"><a href="blog/{post['slug']}.html">{escape(post['title'])}</a></div>
        <div class="muted">{post['date']} · {escape(post['category'])} · {escape(post['venue'])} · {escape(post['status'])}</div>
        <p>{escape(post['summary'])}</p>
    </div>''')
    index = ROOT / 'index.html'
    homepage = index.read_text()
    block = START + '\n' + '\n\n'.join(entries) + '\n    ' + END
    if START not in homepage:
        # Only insert within the existing Blog section; never rebuild the rest of the homepage.
        match = re.search(r'(<section\s+id="blog"[^>]*>)(.*?)(</section>)', homepage, re.S)
        if not match:
            raise ValueError('Missing Blog section')
        homepage = homepage[:match.end(2)] + '\n    ' + block + '\n\n' + homepage[match.end(2):]
    else:
        if homepage.count(START) != 1 or homepage.count(END) != 1:
            raise ValueError('Invalid Blog markers')
        homepage = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda _: block, homepage, flags=re.S)
    result[index] = homepage
    return result

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Verify generated files are current without writing')
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        if not path.exists() or path.read_text() != text:
            if args.check:
                stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
                print(f'Updated {path.relative_to(ROOT)}')
    if stale:
        print('Run python scripts/build_blog.py: ' + ', '.join(stale), file=sys.stderr)
        return 1
    print('Blog output is current.')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
